"""Exposure to partners' demand. Philippine value added embedded in each partner's final demand.

NOT FOR CITATION (research, 23 Oct 2026). For the world-demand side of the 2026 shocks, which the one-country CGE cannot
split by partner.

Run (data extracted under %TEMP%, never in this repository; python -I because the CSV is a third-party file):
    py -I research/icio/partner_demand_exposure_2022.py <path of 2022_SML.csv> [<path of 2018_SML.csv>]

Method (value added in final demand; Johnson and Noguera 2012, J. International Economics 86(2); OECD TiVA's
'domestic value added embodied in foreign final demand'): with the global coefficients A = Z / x (81 economies x 50
industries) and the Leontief inverse L = (I - A)^-1, the Philippine value added generated by the final demand of area c is
    VA_PHL(c) = v_PHL' L y_c,
v_PHL = value added per unit of output of the Philippine industries (zero elsewhere) and y_c = c's final demand for every
area-industry's output (households, non-profits, government, fixed capital, inventories, direct purchases abroad). Summed over
all areas (the Philippines included) it equals Philippine value added at basic prices (checked). By Philippine industry i:
v_i (L y_c)_i. The rows of L for the Philippine industries come from one LU factorization of (I - A)'.
Reading: a 1% fall in the final demand of area c (all components, all products) lowers Philippine value added by
VA_PHL(c) / VA_PHL percent, before any price, exchange-rate or income response (a first-order, fixed-coefficient elasticity).
Gross exports (intermediate and final, to each area) are shown beside it: value added follows final buyers, so it shifts
from processing hubs (China, ASEAN) towards the final markets (United States, Europe) compared with gross exports.
Caveats: current US dollars, 2022 (one year; 2018 as a check); the Philippine block rests on PSA's benchmark tables (2018 the
latest) and the OECD's estimates since; fixed coefficients; no re-imports of Philippine value added netted out of the
Philippines' own final demand (the 'own final demand' row includes value added that went abroad and came back).
"""
from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import numpy as np                                   # noqa: E402
import pandas as pd                                  # noqa: E402
from scipy.linalg import lu_factor, lu_solve         # noqa: E402

import icio_common as IC                             # noqa: E402


def exposure(t: IC.ICIO, home: str = "PHL") -> dict:
    X = np.where(t.X > 0, t.X, 1.0)
    A = t.Z / X[None, :]
    v = t.VA / X
    n = A.shape[0]
    lu = lu_factor((np.eye(n) - A).T)                # rows of L: L' e_i = solve((I - A)', e_i)
    b = t.block(home)
    E = np.zeros((n, len(b)))
    E[b, np.arange(len(b))] = 1.0
    LP = lu_solve(lu, E).T                           # Philippine rows of L (50 x n)
    yc = {a: t.Y[:, t.fd_cols(a)].sum(axis=1) for a in t.areas}
    va_i = {a: v[b] * (LP @ yc[a]) for a in t.areas}  # Philippine value added by industry, generated by a's final demand
    by_area = pd.DataFrame({a: va_i[a] for a in t.areas}, index=t.inds)
    # gross exports of the home area to each area: intermediate + final
    gx = {}
    for a in t.areas:
        if a == home:
            continue
        gx[a] = float(t.Z[np.ix_(b, t.block(a))].sum() + t.Y[np.ix_(b, t.fd_cols(a))].sum())
    va_total = float(t.VA[b].sum())
    check = float(abs(by_area.to_numpy().sum() - va_total))
    check_i = float(np.abs(by_area.sum(axis=1).to_numpy() - t.VA[b]).max())
    return dict(by_area=by_area, gross_exports=pd.Series(gx), va_total=va_total, check=check, check_i=check_i,
                fd_total={a: float(yc[a].sum()) for a in t.areas})


def group_tables(res: dict, home: str = "PHL") -> tuple:
    ba = res["by_area"]
    va_area = ba.sum(axis=0)
    grp = pd.Series({a: IC.partner_group(a) for a in ba.columns})
    va_g = va_area.groupby(grp).sum().reindex(IC.GROUP_ORDER)
    gx_g = res["gross_exports"].groupby(grp.reindex(res["gross_exports"].index)).sum().reindex(IC.GROUP_ORDER)
    foreign = va_g.drop("Philippines (own final demand)").sum()
    tab = pd.DataFrame({
        "PHL value added in its final demand (US$ bn)": va_g / 1000,
        "share of PHL value added (%)": va_g / res["va_total"] * 100,
        "share of PHL value added in foreign final demand (%)": va_g / foreign * 100,
        "PHL gross exports to it (US$ bn)": gx_g / 1000,
        "share of PHL gross exports (%)": gx_g / res["gross_exports"].sum() * 100,
    })
    tab.loc["Philippines (own final demand)", "share of PHL value added in foreign final demand (%)"] = np.nan
    tab.loc["All foreign final demand"] = [foreign / 1000, foreign / res["va_total"] * 100, 100.0,
                                           res["gross_exports"].sum() / 1000, 100.0]
    # by industry: value added by partner group, and the share of each industry's value added that foreign demand buys
    ind = ba.T.groupby(grp).sum().T.reindex(columns=IC.GROUP_ORDER)
    ind_share = ind.div(ba.sum(axis=1), axis=0) * 100
    ind_share["all foreign final demand (%)"] = 100 - ind_share["Philippines (own final demand)"]
    ind_share.insert(0, "industry value added (US$ mn)", ba.sum(axis=1))
    ind_share.insert(1, "name", [IC.INDUSTRY_NAMES[k] for k in ind_share.index])
    top_areas = pd.DataFrame({"PHL value added in its final demand (US$ mn)": va_area,
                              "share of PHL value added (%)": va_area / res["va_total"] * 100,
                              "PHL gross exports to it (US$ mn)": res["gross_exports"].reindex(va_area.index),
                              "group": grp}).sort_values("PHL value added in its final demand (US$ mn)", ascending=False)
    return tab, ind_share, top_areas


def main():
    IC.utf8_stdout()
    args = [a for a in sys.argv[1:] if a.lower().endswith(".csv")]
    if not args:
        args = [str(IC.csv_path(2022))]
    years = {2022: IC.csv_path(2022, [args[0]])}
    if len(args) > 1:
        years[2018] = IC.csv_path(2018, [args[1]])
    stamp = dt.datetime.now().strftime("%Y%m%d_%H%M")
    out, L = {}, []
    for y, p in years.items():
        t = IC.load(p, y)
        res = exposure(t)
        out[y] = (res,) + group_tables(res)
    res22, tab22, ind22, top22 = out[2022]
    base = f"icio_partner_demand_exposure_{stamp}"
    tab22.to_csv(IC.OUT_DIR / f"{base}_by_partner_2022.csv")
    ind22.to_csv(IC.OUT_DIR / f"{base}_by_industry_2022.csv")
    top22.to_csv(IC.OUT_DIR / f"{base}_by_area_2022.csv")
    L += [f"# Exposure to partners' demand: Philippine value added in each partner's final demand (b), "
          f"{dt.datetime.now():%d %b %Y %H:%M}", "",
          "**NOT FOR CITATION** (research). Script: `research/icio/partner_demand_exposure_2022.py` (method and caveats in its "
          "notes). Data: OECD (2025), OECD Inter-Country Input-Output Tables, https://oe.cd/icio (small version, read from a copy "
          "outside this repository; terms of use not stated). Current US dollars.", "",
          f"Checks: Philippine value added 2022 US${res22['va_total'] / 1000:,.1f} bn; value added in all areas' final demand "
          f"minus that total: {res22['check']:.2e} (US$ mn); largest gap by industry {res22['check_i']:.2e}.", "",
          "## 2022, by partner", "", tab22.to_markdown(floatfmt=",.2f"), "",
          "Reading: a 1% fall in a partner's final demand lowers Philippine value added by its 'share of PHL value added' "
          "divided by 100, in percent (first order, fixed coefficients).", ""]
    if 2018 in out:
        tab18 = out[2018][1]
        both = pd.DataFrame({"2018 share of PHL value added (%)": tab18["share of PHL value added (%)"],
                             "2022 share of PHL value added (%)": tab22["share of PHL value added (%)"],
                             "2018 share of gross exports (%)": tab18["share of PHL gross exports (%)"],
                             "2022 share of gross exports (%)": tab22["share of PHL gross exports (%)"]})
        both.to_csv(IC.OUT_DIR / f"{base}_2018_vs_2022.csv")
        L += ["## 2018 against 2022", "", both.to_markdown(floatfmt=",.2f"), ""]
    L += ["## The 15 largest final buyers of Philippine value added, 2022", "",
          top22.head(16).to_markdown(floatfmt=",.1f"), "",
          "## By Philippine industry, 2022: share of the industry's value added bought by each partner's final demand (%)", "",
          ind22.sort_values("all foreign final demand (%)", ascending=False).to_markdown(floatfmt=",.1f"), "",
          f"Derived tables: `outputs/{base}_*.csv`.", ""]
    rep = IC.OUT_DIR / f"{base}.md"
    rep.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))
    print(f"\nWrote {rep}")


if __name__ == "__main__":
    main()
